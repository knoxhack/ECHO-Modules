import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const DEFAULT_REPORT = path.join('reports', 'runtime-parity', 'echo-module-runtime-parity-audit.json')
const DOC_START = '<!-- runtime-parity-baseline:start -->'
const DOC_END = '<!-- runtime-parity-baseline:end -->'

async function exists(filePath) {
  try {
    await fs.access(filePath)
    return true
  } catch {
    return false
  }
}

async function readJson(filePath) {
  const text = await fs.readFile(filePath, 'utf8')
  return JSON.parse(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text)
}

function cleanList(value) {
  return Array.isArray(value)
    ? value.filter((item) => typeof item === 'string' && item.trim().length > 0).map((item) => item.trim())
    : []
}

function object(value) {
  return value && typeof value === 'object' && !Array.isArray(value) ? value : {}
}

async function moduleVersions(repoRoot) {
  const versions = new Map()
  const addonsRoot = path.join(repoRoot, 'addons')
  const entries = await fs.readdir(addonsRoot, { withFileTypes: true })
  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    const descriptorPath = path.join(addonsRoot, entry.name, 'src', 'main', 'resources', 'META-INF', 'echo.mod.json')
    if (!(await exists(descriptorPath))) continue
    const descriptor = await readJson(descriptorPath)
    if (typeof descriptor.id === 'string' && typeof descriptor.version === 'string') {
      versions.set(descriptor.id, descriptor.version)
    }
  }
  return versions
}

function defaultArtifactName(moduleId, version, family) {
  if (family === 'echo-addon') return `${moduleId}-${version}.echo-addon`
  if (family === 'standalone') return `${moduleId}-${version}-standalone.jar`
  return `${moduleId}-${version}-neoforge.jar`
}

function defaultArtifactPath(assetName, family) {
  if (family === 'echo-addon') return `addons/${assetName}`
  return `mods/${assetName}`
}

function versionFor(moduleId, versions, useRange) {
  const version = versions.get(moduleId)
  if (!version) throw new Error(`No descriptor version found for missing baseline module ${moduleId}`)
  return useRange ? `>=${version}` : version
}

function requirementFor({ moduleId, version, family, richStyle }) {
  if (!richStyle) return { id: moduleId, version, required: true }
  const exactVersion = version.replace(/^>=/, '')
  const assetName = defaultArtifactName(moduleId, exactVersion, family)
  return {
    id: moduleId,
    version: exactVersion,
    artifactFamily: family,
    artifactName: assetName,
    assetName,
    path: defaultArtifactPath(assetName, family),
    required: true,
    side: 'both',
  }
}

function sortRequirements(requirements) {
  return requirements.sort((left, right) => String(left.id).localeCompare(String(right.id)))
}

function upsertRequirements(manifest, missingModules, versions) {
  if (!Array.isArray(manifest.moduleRequirements)) manifest.moduleRequirements = []
  const family = typeof manifest.moduleArtifactFamily === 'string' && manifest.moduleArtifactFamily
    ? manifest.moduleArtifactFamily
    : 'echo-addon'
  const existingIds = new Set(manifest.moduleRequirements.map((requirement) => requirement?.id).filter(Boolean))
  const richStyle = manifest.moduleRequirements.some((requirement) =>
    object(requirement).artifactFamily || object(requirement).assetName || object(requirement).path)
  const useRange = !richStyle && manifest.moduleRequirements.some((requirement) =>
    typeof requirement?.version === 'string' && requirement.version.startsWith('>='))
  const added = []
  for (const moduleId of missingModules) {
    if (existingIds.has(moduleId)) continue
    const requirement = requirementFor({
      moduleId,
      version: versionFor(moduleId, versions, useRange),
      family,
      richStyle,
    })
    manifest.moduleRequirements.push(requirement)
    existingIds.add(moduleId)
    added.push(moduleId)
  }
  sortRequirements(manifest.moduleRequirements)
  return { added, family }
}

function docsSection({ repo, family, added, manifest }) {
  const requirements = manifest.moduleRequirements
    .filter((requirement) => requirement?.required !== false)
    .map((requirement) => `- \`${requirement.id}\` (${requirement.version ?? 'unversioned'})`)
    .join('\n')
  const addedText = added.length > 0
    ? added.map((moduleId) => `\`${moduleId}\``).join(', ')
    : 'No new baseline modules were required by the latest sync.'
  return [
    DOC_START,
    '## Runtime Parity Baseline',
    '',
    'Generated by `node scripts/apply-runtime-parity-pack-baseline.mjs` from the ECHO module runtime parity audit.',
    '',
    `- Source audit: \`ECHO-Modules/reports/runtime-parity/echo-module-runtime-parity-audit.json\``,
    `- Module artifact family: \`${family}\``,
    `- Latest added baseline modules for \`${repo}\`: ${addedText}`,
    '',
    'Required modules after the parity sync:',
    '',
    requirements,
    DOC_END,
    '',
  ].join('\n')
}

async function upsertDocs(repoRoot, context) {
  const docsPath = path.join(repoRoot, 'docs', 'module-requirements.md')
  await fs.mkdir(path.dirname(docsPath), { recursive: true })
  const section = docsSection(context)
  if (!(await exists(docsPath))) {
    const title = `# ${context.repo.replace(/^ECHO-/, '').replace(/-/g, ' ')} Module Requirements`
    await fs.writeFile(docsPath, `${title}\n\n${section}`, 'utf8')
    return docsPath
  }
  const current = await fs.readFile(docsPath, 'utf8')
  const start = current.indexOf(DOC_START)
  const end = current.indexOf(DOC_END)
  if (start >= 0 && end > start) {
    const after = end + DOC_END.length
    await fs.writeFile(docsPath, `${current.slice(0, start)}${section}${current.slice(after).replace(/^\s+/, '')}`, 'utf8')
    return docsPath
  }
  const spacer = current.endsWith('\n') ? '\n' : '\n\n'
  await fs.writeFile(docsPath, `${current}${spacer}${section}`, 'utf8')
  return docsPath
}

export async function applyRuntimeParityPackBaseline({
  repoRoot = process.cwd(),
  echoRoot = path.dirname(path.resolve(repoRoot)),
  reportPath = DEFAULT_REPORT,
} = {}) {
  const normalizedRoot = path.resolve(repoRoot)
  const normalizedEchoRoot = path.resolve(echoRoot)
  const report = await readJson(path.resolve(normalizedRoot, reportPath))
  const versions = await moduleVersions(normalizedRoot)
  const changes = []
  for (const manifest of report.packAudit.preferredManifests) {
    const missing = cleanList(manifest.missingBaselineModules)
    if (missing.length === 0) continue
    const packRepoRoot = path.join(normalizedEchoRoot, manifest.repo)
    const manifestPath = path.join(packRepoRoot, manifest.manifestPath)
    const packManifest = await readJson(manifestPath)
    const { added, family } = upsertRequirements(packManifest, missing, versions)
    if (added.length === 0) continue
    await fs.writeFile(manifestPath, `${JSON.stringify(packManifest, null, 2)}\n`, 'utf8')
    const docsPath = await upsertDocs(packRepoRoot, {
      repo: manifest.repo,
      family,
      added,
      manifest: packManifest,
    })
    changes.push({
      repo: manifest.repo,
      manifestPath,
      docsPath,
      added,
    })
  }
  return changes
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  try {
    const changes = await applyRuntimeParityPackBaseline()
    for (const change of changes) {
      console.log(`${change.repo}: added ${change.added.join(', ')}`)
    }
    console.log(`Updated pack baseline manifest(s): ${changes.length}`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
